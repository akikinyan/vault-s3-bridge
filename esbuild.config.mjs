import esbuild from 'esbuild';
import process from 'process';
import { builtinModules } from 'node:module';
import { writeFileSync } from 'node:fs';

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === 'production';

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ['src/main.ts'],
	bundle: true,
	// Desktop-only plugin: resolve packages to their Node.js builds (not browser builds).
	platform: 'node',
	// Never ship the SDK's default credential chain (environment variables, static keys,
	// credential_process). Clients always receive explicit SSO credentials.
	alias: {
		'@aws-sdk/credential-provider-node': './src/aws/noDefaultCredentials.ts',
	},
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtinModules,
		...builtinModules.map((m) => `node:${m}`),
	],
	format: 'cjs',
	target: 'es2021',
	logLevel: 'info',
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	outfile: 'main.js',
	// Keep distributed code readable for community review.
	minify: false,
	// Read by scripts/check-bundle.mjs: which source files import which modules.
	metafile: prod,
});

if (prod) {
	const result = await context.rebuild();
	writeFileSync('.esbuild-meta.json', JSON.stringify(result.metafile));
	process.exit(0);
} else {
	await context.watch();
}
